#Create a NumPy array named prices with these values: [299, 499, 799, 0, 1599, -1, 899]. Print the array and its data type.

import numpy as np

prices = np.array([299, 499, 799, 0, 1599, -1, 899])
print("Prices:", prices)
print("Data type:", prices.dtype)

#Some entries in the prices array are invalid (0 or negative). Replace all values less than or equal to zero with the average of the
#remaining positive prices.<br><br><em><strong>Hint:</strong>Use boolean indexing and the mean() function.</em>


prices = np.array([299, 499, 799, 0, 1599, -1, 899])
avg = prices[prices > 0].mean()
prices[prices <= 0] = avg
print("Updated prices:", prices)
print("Average:", avg)

